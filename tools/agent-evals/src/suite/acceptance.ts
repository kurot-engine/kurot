import { readFile, readdir, rm } from 'node:fs/promises';
import path from 'node:path';
import { assertProtected } from '../comparison/context.js';
import { runProcess } from '../comparison/process.js';
import type { Check } from '../comparison/types.js';
import { resourceChecks } from './resources.js';
import { tweenChecks } from './tween.js';
import { kuiChecks } from './kui.js';
import type { TaskKind } from './types.js';

async function sourceFiles(root: string): Promise<string[]> {
	const result: string[] = [];
	for (const entry of await readdir(root, { withFileTypes: true })) {
		const file = path.join(root, entry.name);
		if (entry.isDirectory()) { result.push(...await sourceFiles(file)); }
		else if (file.endsWith('.ts')) { result.push(await readFile(file, 'utf8')); }
	}
	return result;
}

export async function suiteAcceptance(directory: string, artifacts: string, expected: Record<string, string>, task: TaskKind): Promise<Check[]> {
	const checks: Check[] = [];
	try {
		await assertProtected(directory, expected, task === 'kui' ? ['src/', 'template/web/', 'resource/ui/'] : ['src/', 'template/web/']);
		checks.push({ id: 'integrity', passed: true, detail: 'Read-only fixture, documents and config unchanged.' });
	} catch (error) { return [{ id: 'integrity', passed: false, detail: String(error) }]; }
	const source = (await sourceFiles(path.join(directory, 'src'))).join('\n');
	const publicApi = !/as any\b|@ts-ignore|@ts-expect-error|\.\$[A-Za-z]/.test(source) &&
		(task !== 'resources' || (/\bloadConfig\s*\(/.test(source) && /\bloadGroup\s*\(/.test(source) && /\bBitmap\b/.test(source) && !/\bfetch\s*\(|new XMLHttpRequest/.test(source))) &&
		(task !== 'tween' || source.includes('@kurot/game'));
	checks.push({ id: 'public-sdk', passed: publicApi, detail: publicApi ? 'Required public SDK usage found; no any/suppression/internal access.' : 'Use the required public Resource/Bitmap or Game Tween APIs; avoid any and internal APIs.' });
	await rm(path.join(directory, '.kurot'), { recursive: true, force: true });
	await rm(path.join(directory, 'bin-debug'), { recursive: true, force: true });
	for (const [id, args] of [
		['build', ['--import', 'tsx', 'node_modules/@kurot/cli/dist/index.js', 'build']],
		['typecheck', ['node_modules/typescript/bin/tsc', '--noEmit']],
	] as const) {
		const prefix = path.join(artifacts, id);
		const result = await runProcess(process.execPath, args, directory, prefix, 60000);
		const detail = result.code === 0 ? 'Passed.' : (await readFile(`${prefix}.stdout`, 'utf8')) + (await readFile(`${prefix}.stderr`, 'utf8'));
		checks.push({ id, passed: result.code === 0 && !result.timedOut, detail });
	}
	if (task === 'kui' && checks.find(check => check.id === 'build')?.passed) {
		try {
			const declaration = await readFile(path.join(directory, '.kurot/skin-parts.d.ts'), 'utf8');
			const valid = ['QuizSkin', 'scoreLabel', 'promptLabel', 'start', 'left', 'right', 'restart'].every(id => declaration.includes(`"${id}"`));
			checks.push({ id: 'generated-parts', passed: valid, detail: valid ? 'Required XML parts generated by the real compiler.' : 'Missing QuizSkin required generated parts.' });
		} catch (error) { checks.push({ id: 'generated-parts', passed: false, detail: String(error) }); }
	}
	if (checks.some(check => !check.passed)) return checks;
	try {
		checks.push(...await ({ resources: resourceChecks, tween: tweenChecks, kui: kuiChecks })[task](directory, artifacts));
	} catch (error) { checks.push({ id: 'browser-infrastructure', passed: false, detail: String(error) }); }
	return checks;
}
